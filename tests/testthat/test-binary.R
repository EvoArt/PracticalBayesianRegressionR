# brm(model, data) end to end with a fake executable (a shell script)
test_that("a compiled model runs without Julia and gives a full fit", {
  skip_on_os("windows")
  store <- tempfile("store")
  fake_model(store, "m", priors = "b||||||normal(0, 2)||")
  m <- compiled_model("m", store)
  d <- sim_data(50)
  fit <- brm(m, d, chains = 2, iter = 6, warmup = 3, seed = 1, silent = 2)
  expect_s3_class(fit, "pbrfit")
  expect_equal(fit$backend, "binary")
  expect_equal(fit$nobs, 50L)
  expect_equal(variables(fit), c("b_x", "sigma"))
  expect_equal(dim(fit$draws), c(3L, 2L, 2L))
  expect_equal(as.vector(fit$draws[, 2, "b_x"]), c(0.21, 0.22, 0.23))
  expect_equal(dim(fit$theta), c(3L, 2L, 2L))
  expect_equal(fit$times, c(0.25, 0.5))
  expect_equal(fit$prior$prior, "normal(0, 2)")
  expect_equal(ndraws(fit), 6)
  expect_s3_class(as_draws_df(fit), "draws_df")
  expect_equal(nrow(posterior::summarise_draws(as_draws_array(fit))), 2)
  # dispatch from inside posterior's namespace: the methods must be registered, not just exported
  expect_equal(nrow(posterior::summarise_draws(fit)), 2)
  expect_equal(posterior::ndraws(fit), 6)
  expect_equal(rownames(fixef(fit)), "x")
  np <- nuts_params(fit)
  expect_setequal(levels(np$Parameter), c("lp__", "accept_stat__", "stepsize__", "treedepth__",
                                          "n_leapfrog__", "divergent__", "energy__"))
  expect_output(print(fit), "Regression Coefficients")
  expect_output(print(fit), "compiled model `m`")
  # update with new data reruns the executable
  fit2 <- update(fit, newdata = sim_data(30, 2))
  expect_equal(fit2$nobs, 30L)
  expect_equal(fit2$backend, "binary")
  # thinning is applied to the saved draws
  expect_equal(dim(brm(m, d, chains = 2, iter = 6, warmup = 3, thin = 2, silent = 2)$draws)[1], 2L)
  # file caching, as brms
  f <- tempfile()
  a <- brm(m, d, chains = 2, iter = 6, warmup = 3, file = f, silent = 2)
  expect_true(file.exists(paste0(f, ".rds")))
  expect_identical(brm(m, d, chains = 2, iter = 6, warmup = 3, file = f, silent = 2)$draws, a$draws)
})

test_that("backend = 'auto' picks a stored model for the same specification", {
  skip_on_os("windows")
  store <- tempfile("store")
  d <- sim_data(40)
  key <- pbr$r_model_key(bf(y ~ x + (1 | g)), d, gaussian(), NULL)
  fake_model(store, "auto_m", keys = key)
  old <- Sys.getenv("PBR_MODEL_STORE")
  Sys.setenv(PBR_MODEL_STORE = store)
  on.exit(Sys.setenv(PBR_MODEL_STORE = old))
  fit <- brm(y ~ x + (1 | g), d, chains = 2, iter = 6, warmup = 3, silent = 2)
  expect_equal(fit$backend, "binary")
  expect_equal(fit$model$name, "auto_m")
})

test_that("a failing executable reports its output", {
  skip_on_os("windows")
  store <- tempfile("store")
  dir <- fake_model(store, "bad")
  writeLines(c("#!/bin/sh", "echo 'error: something broke' >&2", "exit 1"), file.path(dir, "bin", "bad"))
  expect_error(brm(compiled_model("bad", store), sim_data(), silent = 2), "something broke")
})

test_that("a model loads by name, directory or executable path, and is callable", {
  skip_on_os("windows")
  store <- tempfile("store")
  dir <- fake_model(store, "mymod")
  d <- sim_data(40)
  mymod <- load_model("mymod", store)
  expect_s3_class(mymod, "pbr_model_fn")
  expect_output(print(mymod), "Compiled model `mymod`")
  fit <- mymod(d, chains = 2, iter = 6, warmup = 3, silent = 2)
  expect_s3_class(fit, "pbrfit")
  expect_equal(fit$model$name, "mymod")
  expect_equal(fit$nobs, 40L)
  expect_equal(brm(mymod, d, chains = 2, iter = 6, warmup = 3, silent = 2)$model$name, "mymod")
  # the executable's path, or the directory (e.g. a model copied elsewhere), work too
  exe <- file.path(dir, "bin", "mymod")
  expect_equal(compiled_model(exe)$name, "mymod")
  expect_equal(attr(load_model(exe), "model")$dir, attr(mymod, "model")$dir)
  moved <- file.path(tempfile("elsewhere"), "copy")
  dir.create(dirname(moved))
  file.copy(dir, dirname(moved), recursive = TRUE)
  file.rename(file.path(dirname(moved), "mymod"), moved)
  expect_equal(load_model(moved)(d, chains = 2, iter = 6, warmup = 3, silent = 2)$nobs, 40L)
  expect_error(load_model("nope", store), "no compiled model")
  expect_error(compiled_model(file.path(tempdir(), "no", "such", "model.exe"), store), "no compiled model")
})
